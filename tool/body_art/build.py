"""Writes lib/ui/train/muscle_art.dart from the body artwork in this folder.

front.svg and side.svg are the supplied drawings; every shape gets an id
(f<n>, s<n>) so the app can colour a muscle. back.svg is drawn to match
(make_back.py), its muscles already named. Run from the repo root:

  python3 tool/body_art/build.py
"""
import re

def tagged(path, prefix):
    svg = open(path).read().strip()
    if prefix is None:
        return svg
    n = iter(range(10**6))
    return re.sub(r'<path ', lambda _: f'<path id="{prefix}{next(n)}" ', svg)

out = ['// Generated by tool/body_art/build.py: the body artwork, front, back and',
       '// side, with an id on every shape a muscle can light up.', '']
for name, file, prefix in [('front', 'front.svg', 'f'), ('back', 'back.svg', None), ('side', 'side.svg', 's')]:
    svg = tagged(f'tool/body_art/{file}', prefix)
    assert "'''" not in svg
    out.append(f"const {name}BodySvg = r'''{svg}''';")
    out.append('')
open('lib/ui/train/muscle_art.dart', 'w').write('\n'.join(out))
