"""Iron's pixel art: one source, two outputs.

    python3 tool/iron_art.py

tool/iron/art.json holds Iron's bodies (25 x 25 grids, one letter per
colour), the faces and extras laid over them, and the still poses. This
writes lib/ui/common/iron_art.g.dart for the app, which draws and animates
Iron from it, and design/iron/iron-<pose>.svg for design work.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
art = json.loads((ROOT / "tool/iron/art.json").read_text())
N = art["size"]


def dart() -> str:
    q = lambda s: "'" + s + "'"
    out = ["// Generated by tool/iron_art.py from tool/iron/art.json. Do not edit.", "",
           "const ironSize = %d;" % N, "", "const ironPalette = <String, int>{"]
    for k, v in art["palette"].items():
        out.append("  %s: 0xFF%s," % (q(k), v.lstrip("#").upper()))
    out += ["};", "", "const ironBodies = <String, List<String>>{"]
    for name, rows in art["bodies"].items():
        out.append("  %s: [" % q(name))
        out += ["    %s," % q(r) for r in rows]
        out.append("  ],")
    out += ["};", "", "const ironHopDy = %d;" % art["hop_dy"], ""]
    for group in ("faces", "extras"):
        out.append("const iron%s = <String, List<(int, int, String)>>{" % group.capitalize())
        for name, px in art[group].items():
            out.append("  %s: [%s]," % (q(name), ", ".join("(%d, %d, %s)" % (x, y, q(c)) for x, y, c in px)))
        out += ["};", ""]
    return "\n".join(out)


def svg(body: str, face, extras) -> str:
    cells = {}
    for y, row in enumerate(art["bodies"][body]):
        for x, c in enumerate(row):
            if c != ".":
                cells[(x, y)] = c
    for x, y, c in (art["faces"][face] if face else []):
        cells[(x, y)] = c
    for e in extras:
        for x, y, c in art["extras"][e]:
            cells[(x, y)] = c
    rects = "".join(
        '<rect x="%d" y="%d" width="1.02" height="1.02" fill="%s"/>' % (x, y, art["palette"][c])
        for (x, y), c in sorted(cells.items(), key=lambda kv: (kv[0][1], kv[0][0]))
    )
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" shape-rendering="crispEdges">%s</svg>\n'
            % (N, N, rects))


def main():
    (ROOT / "lib/ui/common/iron_art.g.dart").write_text(dart() + "\n")
    out = ROOT / "design/iron"
    out.mkdir(parents=True, exist_ok=True)
    for pose, (body, face, extras) in art["poses"].items():
        (out / f"iron-{pose}.svg").write_text(svg(body, face, extras))
    print("wrote lib/ui/common/iron_art.g.dart and", len(art["poses"]), "SVGs in design/iron")


if __name__ == "__main__":
    main()
