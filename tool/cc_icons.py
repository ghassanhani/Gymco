"""The Control Center's icons, from the Gymco icon library (rounded, outline).

    python3 tool/cc_icons.py ../icons-library

Writes site/admin/lib/icons.js: each icon as a list of [tag, attributes]
for dom.js to draw with createElementNS, so no SVG is ever parsed from a
string. Colours become currentColor; Figma's clip-path wrappers are dropped
(every shape already sits inside the 24 x 24 box).
"""

import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# Control Center name -> icon library name.
ICONS = {
    # sidebar
    "overview": "dashboard-square-01",
    "health": "cardiogram-02",
    "accounts": "user",
    "support": "inbox",
    "config": "sliders-horizontal",
    "content": "layers-01",
    "plans": "tag-01",
    "messaging": "megaphone-02",
    "releases": "rocket-01",
    "website": "browser",
    "team": "user-group",
    # top bar and locks
    "menu": "menu-01",
    "search": "search-01",
    "sun": "sun-03",
    "moon": "moon-02",
    "lock": "square-lock-02",
    # Overview tiles
    "k-accounts": "user-group",
    "k-signups": "user-add-01",
    "k-active": "cloud-saving-done-01",
    "k-scans": "camera-01",
    "k-cost": "euro",
    "k-cap": "dashboard-speed-01",
    "k-deletions": "user-remove-01",
    "k-db": "database",
    # System health tiles
    "k-crash": "bug-01",
    "k-errors": "alert-02",
    "k-storage": "cloud",
}
SHAPES = {"path", "circle", "ellipse", "rect", "line", "polyline", "polygon"}
KEEP = {"d", "cx", "cy", "r", "rx", "ry", "x", "y", "width", "height", "x1", "y1", "x2", "y2", "points", "transform",
        "fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin", "fill-rule", "clip-rule", "opacity", "fill-opacity", "stroke-opacity"}


def shapes(el):
    for c in el:
        tag = c.tag.split("}")[-1]
        if tag == "defs":
            continue
        if tag == "g":
            yield from shapes(c)
        elif tag in SHAPES:
            a = {k: v for k, v in c.attrib.items() if k in KEEP}
            for k in ("fill", "stroke"):
                if k in a and a[k] not in ("none",):
                    a[k] = "currentColor"
            yield [tag, a]


def main(lib: Path) -> None:
    out = {}
    for name, src in ICONS.items():
        root = ET.parse(lib / "svgs/rounded/stroke" / f"{src}.svg").getroot()
        out[name] = list(shapes(root))
        assert out[name], name
    body = ",\n".join(f"  {json.dumps(k)}: {json.dumps(v, separators=(',', ':'))}" for k, v in out.items())
    (ROOT / "site/admin/lib/icons.js").write_text(
        "// Generated by tool/cc_icons.py from the Gymco icon library (rounded, outline). Don't edit by hand.\n"
        "// Each icon is a list of [tag, attributes] drawn by icon() in dom.js.\n\n"
        f"export const ICONS = {{\n{body},\n}};\n")
    print("wrote", len(out), "icons")


if __name__ == "__main__":
    main(Path(sys.argv[1] if len(sys.argv) > 1 else ROOT.parent / "icons-library"))
