"""Writes site/admin/lib/notes_catalog.js: every notification the app
schedules, when it goes, and its built-in words in each language, read
from the app's own translation files so the Control Center shows exactly
what phones say. Run from the repo root after changing a notification:

  python3 tool/notes_catalog.py
"""
import json, re

arb = {l: json.load(open(f'lib/l10n/app_{l}.arb')) for l in ('en', 'ar', 'es')}

def branches(s):
    """(male, female) of an ICU sex select, or the text twice."""
    m = re.fullmatch(r'\{sex, select, female\{(.*)\} other\{(.*)\}\}', s, re.S)
    return (m[2], m[1]) if m else (s, s)

def words(key):
    if key is None:
        return {'en': '{tip}', 'ar': '{tip}', 'ar_f': '{tip}', 'es': '{tip}'}
    en, _ = branches(arb['en'][key])
    ar, ar_f = branches(arb['ar'][key])
    es, _ = branches(arb['es'][key])
    return {'en': en, 'ar': ar, 'ar_f': ar_f, 'es': es}

# kind, group, label, when, title key, body key
KINDS = [
    ('breakfast', 'Daily habit', 'Breakfast', '45 min after breakfast time, if nothing logged', 'nBreakfastT', 'nBreakfastB'),
    ('lunch', 'Daily habit', 'Lunch', '45 min after lunch time, if nothing logged', 'nLunchT', 'nLunchB'),
    ('dinner', 'Daily habit', 'Dinner', '45 min after dinner time, if nothing logged', 'nDinnerT', 'nDinnerB'),
    ('protein', 'Daily habit', 'Protein short', '2 h before dinner, if protein is under 70%', 'nProteinT', 'nProteinB'),
    ('water', 'Daily habit', 'Water', 'Up to 3 a day, only if behind pace', 'nWaterT', 'nWaterB'),
    ('workout', 'Daily habit', 'Workout today', '1 h before the usual training time', 'nWorkoutT', 'nWorkoutB'),
    ('sessionMoved', 'Daily habit', 'Session moved', '21:00 on a training day with no session', 'nMovedT', 'nMovedB'),
    ('weighIn', 'Daily habit', 'Weigh-in', 'Chosen mornings, 07:30 by default', 'nWeighT', 'nWeighB'),
    ('restOver', 'Workout timer', 'Rest over', 'When the rest timer ends · rings through Focus, not counted in the cap', 'nRestT', 'nRestB'),
    ('workoutOpen', 'Workout timer', 'Workout left open', '3 h after the last set', 'nOpenT', 'nOpenB'),
    ('streakRisk', 'Streak & awards', 'Streak at risk', '20:30 if the day isn’t kept yet', 'nStreakT', 'nStreakB'),
    ('freezeUsed', 'Streak & awards', 'Freeze used', '09:00 after a freeze covered a day', 'nFreezeT', 'nFreezeB'),
    ('streakRepair', 'Streak & awards', 'Repair available', '10:00 the day after a missed day', 'nRepairT', 'nRepairB'),
    ('challengeNew', 'Streak & awards', 'New monthly challenge', '1st of the month, 10:00', 'nChallengeT', 'nChallengeB'),
    ('challengeNear', 'Streak & awards', 'Challenge almost done', '19:00 when 2 sessions remain with 5+ days left', 'nNearT', 'nNearB'),
    ('checkIn', 'Progress & coaching', 'Weekly check-in', 'Saturday 10:00 in the Gulf, Monday 09:00 elsewhere', 'nCheckInT', 'nCheckInB'),
    ('ironTip', 'Progress & coaching', 'Iron’s tip', 'Rest days at 12:00, at most 2 a week', 'nIronT', None),
    ('welcomeBack', 'Account & system', 'Welcome back', '3 days after the last thing logged, once', 'nBackT', 'nBackB'),
    ('backup', 'Account & system', 'Backup failed', '3 days after the last backup', 'nBackupT', 'nBackupB'),
]

out = [{'kind': k, 'group': g, 'label': label, 'when': when, 'title': words(t), 'body': words(b)}
       for k, g, label, when, t, b in KINDS]
js = ('// Generated by tool/notes_catalog.py from the app\'s translation files:\n'
      '// every notification, when it goes, and the words phones use when the\n'
      '// Control Center sets none.\n\n'
      f'export const NOTES = {json.dumps(out, ensure_ascii=False, indent=2)};\n')
open('site/admin/lib/notes_catalog.js', 'w').write(js)
print(len(out))
