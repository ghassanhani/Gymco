"""Writes site/admin/tokens.css from the Untitled UI Foundations tokens.json.

    python3 tools/admin_tokens.py <tokens.json> site/admin/tokens.css

Takes the semantic colour layer (text-*, bg-*, fg-*, border-*, shadow-*) for
light and dark, the spacing and radius scales and the type families, and
swaps the stock purple brand ramp for Gymco lime. Exits non-zero if a text
pair falls under 4.5:1 or the chart bars under 3:1, in either theme.
"""

import json
import re
import sys

# Gymco lime. 500 is the app's brand colour; the dark end carries text on white.
LIME = {
    "50": "#F8FEE7", "100": "#EFFCC8", "200": "#E3F99E", "300": "#D6F770", "400": "#CDF54E",
    "500": "#C6F432", "600": "#9CC414", "700": "#5E7A08", "800": "#46590B", "900": "#33410C",
    "950": "#1C2406",
}

# Where Gymco differs from the stock mapping (light, dark). Lime is a light
# colour: the solid brand surface is the app's lime in both themes and takes
# dark ink, the reverse of the stock purple's white.
OVERRIDES = {
    "bg-brand-solid": ("{palette-brand-500}", "{palette-brand-500}"),
    "bg-brand-solid_hover": ("{palette-brand-400}", "{palette-brand-400}"),
    "text-primary_on-brand": ("{palette-neutral-950}", "{palette-neutral-950}"),
    "text-secondary_on-brand": ("{palette-neutral-800}", "{palette-neutral-800}"),
    "text-brand-secondary": ("{palette-brand-700}", "{palette-brand-300}"),
    "text-brand-tertiary": ("{palette-brand-700}", "{palette-brand-400}"),
    # Not in the system: the one series colour the dashboard's bar charts use.
    "chart-bar": ("{palette-brand-700}", "{palette-brand-500}"),
    # Not in the system either: an outline for the one text field. The stock
    # border-primary measures 1.48:1 light and 1.91:1 dark, under the 3:1 a
    # control boundary needs; it is kept as the source has it for dividers.
    "border-control": ("{palette-neutral-500}", "{palette-neutral-500}"),
    # Error copy on the error banner: text-error-primary is 4.41:1 on
    # bg-error-primary in light, one step darker clears 4.5.
    "text-error-banner": ("{palette-red-700}", "{text-error-primary}"),
}

SEMANTIC = re.compile(r"^(text|bg|fg|border|shadow)-")

TEXT_PAIRS = [
    ("text-primary", "bg-primary"), ("text-secondary", "bg-primary"), ("text-tertiary", "bg-primary"),
    ("text-primary", "bg-secondary"), ("text-secondary", "bg-secondary"), ("text-tertiary", "bg-secondary"),
    ("text-brand-secondary", "bg-primary"), ("text-primary_on-brand", "bg-brand-solid"),
    ("text-error-primary", "bg-primary"), ("text-error-banner", "bg-error-primary"),
]
MARK_PAIRS = [("chart-bar", "bg-primary"), ("border-control", "bg-primary")]


def luminance(hex_):
    h = hex_.lstrip("#")[:6]
    rgb = [int(h[i : i + 2], 16) / 255 for i in (0, 2, 4)]
    lin = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in rgb]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def contrast(a, b):
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def main(src, out):
    t = json.load(open(src))
    colors = {c["name"]: c["value"] for c in t["color"]["tokens"]}
    for step, hex_ in LIME.items():
        colors[f"palette-brand-{step}"] = hex_
    for name, (light, dark) in OVERRIDES.items():
        colors[name] = {"light": light, "dark": dark}

    def resolve(name, theme, seen=()):
        v = colors[name]
        if isinstance(v, dict):
            v = v.get(theme, v.get("light"))
        m = re.fullmatch(r"\{(.+)\}", v)
        if m:
            if m[1] in seen:
                raise ValueError(f"alias loop at {name}")
            return resolve(m[1], theme, seen + (name,))
        return v

    names = sorted(n for n in colors if SEMANTIC.match(n) or n in OVERRIDES)
    themes = {th: {n: resolve(n, th) for n in names} for th in ("light", "dark")}

    failures = []
    for th, vals in themes.items():
        for pairs, floor in ((TEXT_PAIRS, 4.5), (MARK_PAIRS, 3.0)):
            for fg, bg in pairs:
                r = contrast(vals[fg], vals[bg])
                if r < floor:
                    failures.append(f"{th}: {fg} on {bg} = {r:.2f}:1 (needs {floor})")

    lines = ["/* Untitled UI Foundations tokens with Gymco lime, generated by tools/admin_tokens.py. */", ":root {"]
    lines += [f"  --{n}: {v};" for n, v in themes["light"].items()]
    for fam in ("spacing", "radius"):
        lines += [f"  --{x['name']}: {x['value']};" for x in t[fam]["tokens"]]
    for k, v in t["type"]["families"].items():
        lines.append(f"  --font-{k}: {v};")
    lines += [
        "  --box-shadow-xs: 0 1px 2px var(--shadow-xs);",
        "  --box-shadow-sm: 0 1px 3px var(--shadow-sm_01), 0 1px 2px -1px var(--shadow-sm_02);",
        "  color-scheme: light dark;",
        "}",
        "@media (prefers-color-scheme: dark) {",
        "  :root {",
    ]
    lines += [f"    --{n}: {v};" for n, v in themes["dark"].items() if v != themes["light"][n]]
    lines += ["  }", "}", ""]
    open(out, "w").write("\n".join(lines))

    for f in failures:
        print("FAIL", f)
    print(f"{len(names)} colour tokens, {len(failures)} contrast failures")
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main(*sys.argv[1:3])
